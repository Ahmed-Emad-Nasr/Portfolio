#!/usr/bin/env python3
"""
scripts/subset-yuji-site.py — one small Yuji Syuku file with exactly the
characters the site writes in it.

app/fonts.ts loads Yuji Syuku through next/font, which serves it as ~120
unicode-range slices; the decorative kanji on the site touch 23 of them
(~620 KB) because the characters are spread across the whole font.
app/fonts-yuji-site.css declares 'Yuji Syuku Site' with this subset and a
unicode-range of exactly these characters, and globals.css puts it first in
the Japanese font stacks, ahead of next/font's family — so for any of them
the browser uses this one small file and never fetches the slices. A
character that is not in the subset falls through to next/font's slices.

The glyphs are the same font (Google Fonts' Yuji Syuku, checked outline for
outline against the slices). Re-run after adding new Japanese text:

    npm pack @expo-google-fonts/yuji-syuku   (extract the .tgz)
    pip install fonttools brotli
    python3 scripts/subset-yuji-site.py <path/to/YujiSyuku_400Regular.ttf>
"""

import pathlib
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_FONT = ROOT / "app" / "fonts" / "yuji-syuku-site.woff2"
OUT_CSS = ROOT / "app" / "fonts-yuji-site.css"


def used_chars() -> set[int]:
    chars: set[int] = set()
    dirs = [ROOT.joinpath(d) for d in ("app", "components", "lib", "data")]
    files = [*(f for d in dirs for f in d.rglob("*.ts*")), *(f for d in dirs for f in d.rglob("*.css"))]
    for f in files:
        if f.name == "fonts-yuji-site.css":
            continue
        text = re.sub(r"/\*.*?\*/", "", f.read_text(encoding="utf8"), flags=re.S)
        for c in text:
            o = ord(c)
            # Kana, kanji, CJK punctuation and full-width forms
            if 0x3000 <= o <= 0x9FFF or 0xFF00 <= o <= 0xFFEF:
                chars.add(o)
    # The Latin and punctuation that appear inside brush / vertical text
    chars.update(range(0x20, 0x7F))
    chars.update([0x00B7, 0x2014, 0x2022, 0x2026])
    return chars


def ranges(cps: list[int]) -> str:
    out, start, prev = [], None, None
    for cp in sorted(cps):
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in out)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    font_cmap = TTFont(src).getBestCmap()
    cps = sorted(c for c in used_chars() if c in font_cmap)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    # Hinting instructions do nothing for a display face at these sizes
    opts.hinting = False
    font = subset.load_font(src, opts)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    subset.save_font(font, str(OUT_FONT), opts)
    OUT_CSS.write_text(
        "/*\n"
        " * Yuji Syuku, cut to the characters the site uses (generated by\n"
        " * scripts/subset-yuji-site.py — do not edit by hand).\n"
        " *\n"
        " * Its own family name (\"Yuji Syuku Site\"), first in the Japanese font\n"
        " * stacks (globals.css), ahead of next/font's \"Yuji Syuku\": for these\n"
        " * characters the browser uses this face, so the Google slices are not\n"
        " * fetched — whatever order the stylesheets end up in. Same glyphs, one\n"
        " * small file. Characters outside this list fall through to next/font.\n"
        " */\n"
        "@font-face {\n"
        "  font-family: 'Yuji Syuku Site';\n"
        "  font-style: normal;\n"
        "  font-weight: 400;\n"
        "  font-display: swap;\n"
        "  src: url(fonts/yuji-syuku-site.woff2) format('woff2');\n"
        f"  unicode-range: {ranges(cps)};\n"
        "}\n",
        encoding="utf8",
    )
    cjk = sum(1 for c in cps if c >= 0x3000)
    print(f"{OUT_FONT.relative_to(ROOT)}: {len(cps)} characters ({cjk} Japanese), {OUT_FONT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
